# ==============================================================================
# setup-db.ps1 — create the database tables and seed the first admin account
#
# Run it from the project folder:
#     .\setup-db.ps1
#
# It asks for your Supabase connection strings (paste them from Supabase),
# saves them to .env, creates the tables, and creates the admin user.
# Nothing here is uploaded anywhere — it all stays on this computer.
# ==============================================================================

$ErrorActionPreference = 'Stop'
Set-Location $PSScriptRoot

$nodeDir = "$env:LOCALAPPDATA\Programs\nodejs\node-v24.22.0-win-x64"
if (Test-Path $nodeDir) { $env:Path = "$nodeDir;$env:Path" }

Write-Host ""
Write-Host "==============================================" -ForegroundColor Cyan
Write-Host " DigitalVault - database setup" -ForegroundColor Cyan
Write-Host "==============================================" -ForegroundColor Cyan
Write-Host ""

# --- 1. Database URLs -------------------------------------------------------

Write-Host "Paste your DATABASE_URL (the POOLED one)." -ForegroundColor Yellow
Write-Host "  It contains  pooler.supabase.com  and ends with /postgres" -ForegroundColor DarkGray
$dbUrl = Read-Host "DATABASE_URL"
if ([string]::IsNullOrWhiteSpace($dbUrl)) { throw "DATABASE_URL cannot be empty." }

Write-Host ""
Write-Host "Paste your DIRECT_URL (the DIRECT one)." -ForegroundColor Yellow
Write-Host "  It contains  db.<ref>.supabase.co  and ends with /postgres" -ForegroundColor DarkGray
$directUrl = Read-Host "DIRECT_URL"
if ([string]::IsNullOrWhiteSpace($directUrl)) { throw "DIRECT_URL cannot be empty." }

if ($dbUrl -notmatch 'pooler\.supabase\.com') {
    Write-Warning "That DATABASE_URL does not contain 'pooler.supabase.com'."
    Write-Warning "On Supabase, pick SESSION POOLER or TRANSACTION POOLER, not Direct Connection."
    Write-Host "Continue anyway? [y/N]" -ForegroundColor Yellow
    if ((Read-Host) -ne 'y') { throw "Stopped." }
}
if ($directUrl -notmatch '/db\.[a-z0-9]+\.supabase\.co/') {
    Write-Warning "That DIRECT_URL does not look like a Supabase direct connection."
    Write-Host "Continue anyway? [y/N]" -ForegroundColor Yellow
    if ((Read-Host) -ne 'y') { throw "Stopped." }
}

# --- 2. Passwords -----------------------------------------------------------

Write-Host ""
$adminPass = Read-Host "Choose a password for the admin account (min 8 chars)" -AsSecureString
$adminPassPlain = [System.Net.NetworkCredential]::new('', $adminPass).Password
if ($adminPassPlain.Length -lt 8) { throw "Admin password is too short (minimum 8 characters)." }

$buyerPass = Read-Host "Choose a password for the demo buyer (min 8 chars)" -AsSecureString
$buyerPassPlain = [System.Net.NetworkCredential]::new('', $buyerPass).Password
if ($buyerPassPlain.Length -lt 8) { throw "Buyer password is too short (minimum 8 characters)." }

# --- 3. Write .env ----------------------------------------------------------

Write-Host ""
Write-Host "Writing .env ..." -ForegroundColor Cyan

$sessionSecret = New-Object byte[] 48
$rng = New-Object System.Security.Cryptography.RNGCryptoServiceProvider
$rng.GetBytes($sessionSecret); $rng.Dispose()
$sessionSecretB64 = [Convert]::ToBase64String($sessionSecret)

$envBody = @"
# Generated by setup-db.ps1 on $(Get-Date -Format 'yyyy-MM-dd HH:mm')
# Gitignored - never committed.

DATABASE_URL="$dbUrl"
DIRECT_URL="$directUrl"
SESSION_SECRET="$sessionSecretB64"
NEXT_PUBLIC_SITE_URL="http://localhost:3000"
SITE_URL="http://localhost:3000"
"@

Set-Content -Path ".env" -Value $envBody -Encoding UTF8
Write-Host "  .env written." -ForegroundColor Green

# --- 4. Create the tables ----------------------------------------------------

Write-Host ""
Write-Host "Creating tables (this can take a minute) ..." -ForegroundColor Cyan
npx.cmd prisma db push
if ($LASTEXITCODE -ne 0) { throw "prisma db push failed - see the error above." }
Write-Host "  Tables created." -ForegroundColor Green

# --- 5. Seed ----------------------------------------------------------------

Write-Host ""
Write-Host "Creating the admin + demo accounts ..." -ForegroundColor Cyan
$env:ADMIN_SEED_PASSWORD = $adminPassPlain
$env:BUYER_SEED_PASSWORD = $buyerPassPlain
npx.cmd tsx --env-file=.env scripts/seed.ts
if ($LASTEXITCODE -ne 0) { throw "Seeding failed - see the error above." }

Remove-Item Env:\ADMIN_SEED_PASSWORD -ErrorAction SilentlyContinue
Remove-Item Env:\BUYER_SEED_PASSWORD -ErrorAction SilentlyContinue

# --- 6. Done ----------------------------------------------------------------

Write-Host ""
Write-Host "==============================================" -ForegroundColor Green
Write-Host " DONE - database is ready" -ForegroundColor Green
Write-Host "==============================================" -ForegroundColor Green
Write-Host ""
Write-Host "  Admin login : admin@asset.shop"
Write-Host "  Password    : $adminPassPlain"
Write-Host ""
Write-Host "  Buyer login : demo@buyer.shop"
Write-Host "  Password    : $buyerPassPlain"
Write-Host ""
Write-Host " NEXT STEP: go to Vercel -> Deployments -> Redeploy." -ForegroundColor Cyan
Write-Host "==============================================" -ForegroundColor Green
Write-Host ""